import { it, expect, vi } from 'vitest';
import Ajv from 'ajv';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { capturePresentationSchema, PRESENTATION_BOUNDS, VictPresentationError, bridgeCapabilityToolToMastra, MASTRA_ADAPTER_REVISION, MASTRA_PINNED_VERSIONS } from '@victframework/mastra';
import { defineContract } from '@victframework/contracts';
import { editPresentation } from '../../../../apps/studio/src/lib/designer/agent-edit-presentation.js';
import { agentReadPresentation } from '../../../../apps/studio/src/lib/designer/agent-reads.js';
import { screenRecipes } from '../../../../apps/studio/src/lib/designer/recipes.js';

it('independently challenges the direct presentation-string amendment through current source', () => {
  const directory = dirname(fileURLToPath(import.meta.url));
  const repository = resolve(directory, '../../../..');
  const git = (...args: string[]) => execFileSync('git', args, { cwd: repository, encoding: 'utf8' }).trim();
  const candidateSHA = git('rev-parse', 'HEAD');
  expect(candidateSHA).toBe('20fb566221a13eb7c68653f299f45c6222666c69');
  expect(git('diff', '--name-only', 'HEAD', '--', 'packages', 'apps/studio')).toBe('');
  expect(git('merge-base', '--is-ancestor', '7152a897cb6b61f8fa32a2db9c60b99ca1f24cab', candidateSHA)).toBe('');
  expect(PRESENTATION_BOUNDS).not.toHaveProperty('maxStringLength');
  expect(PRESENTATION_BOUNDS.maxTotalBytes).toBe(32768);
  expect(MASTRA_ADAPTER_REVISION).toBe('4');
  expect(MASTRA_PINNED_VERSIONS).toEqual({ '@mastra/core': '1.64.0', '@mastra/memory': '1.28.2', '@mastra/libsql': '1.22.3', '@mastra/observability': '1.17.5' });
  const primary = editPresentation.$defs.add.properties as Record<string, { pattern: string }>;
  const pattern = editPresentation.properties.operations.items.properties.recipe.pattern;
  expect(primary.recipe.pattern).toBe(pattern);
  expect(pattern.length).toBeGreaterThan(2048);
  const capturedEdit = capturePresentationSchema(editPresentation, 'independent expanded catalog');
  capturePresentationSchema(agentReadPresentation, 'independent read');
  const ajv = new Ajv({ logger: false, allErrors: true });
  const valid = ajv.compile(capturedEdit);
  const payload = (recipe: unknown) => ({ expectedRevision: 'r1#0', reason: 'Independent amendment challenge', operations: [{ op: 'add', recipe, nodeId: 'new-node', parentId: 'screen' }] });
  const names = screenRecipes.map(recipe => recipe.id), registered = new Set(names);
  for (const name of names) expect(valid(payload(name)), name).toBe(true);
  const adversarial = names.flatMap(name => [`prefix-${name}`, `${name}-suffix`, `${name} `, ` ${name}`, name.replaceAll('.', '/'), name.replaceAll('-', '_')]).filter(name => !registered.has(name));
  const unknown: unknown[] = [...new Set(adversarial), '', 'unregistered', 'dropdown-menuXitem', null, 0, false, [], {}];
  for (const name of unknown) expect(valid(payload(name)), JSON.stringify(name)).toBe(false);
  const inheritedPresentationFindings = names.filter(name => valid(payload(name + '\n'))).map(name => ({ kind: 'trailing-line-feed', registeredName: name }));
  const originalPresentation = git('show', 'd7aeecf8176d78f4e7864a386ac1ff207cb4b871:apps/studio/src/lib/designer/agent-edit-presentation.ts');
  expect(originalPresentation).toBe(readFileSync(resolve(repository, 'apps/studio/src/lib/designer/agent-edit-presentation.ts'), 'utf8').trim());

  const admitted = ['x'.repeat(2049), 'x'.repeat(7000), '界'.repeat(4000), '😀'.repeat(4000), '"'.repeat(7000)];
  for (const text of admitted) expect(capturePresentationSchema({ text }, 'long valid')).toEqual({ text });
  const floor = Buffer.byteLength(JSON.stringify({ s: '' }), 'utf8');
  const exact = { s: 'x'.repeat(32768 - floor) };
  expect(Buffer.byteLength(JSON.stringify(exact), 'utf8')).toBe(32768);
  expect(capturePresentationSchema(exact, 'exact aggregate')).toEqual(exact);
  for (const text of [exact.s + 'x', '界'.repeat(12000), '😀'.repeat(9000), '"'.repeat(17000)]) {
    expect(() => capturePresentationSchema({ s: text }, 'over aggregate')).toThrowError(VictPresentationError);
  }
  const canary = 'NON_ECHO_CANARY_' + 'x'.repeat(32769);
  const stringify = vi.spyOn(JSON, 'stringify');
  let earlyError: unknown;
  try { capturePresentationSchema({ s: canary }, 'early guard'); } catch (error) { earlyError = error; }
  expect(stringify).not.toHaveBeenCalled();
  stringify.mockRestore();
  expect(earlyError).toBeInstanceOf(VictPresentationError);
  expect(String(earlyError)).not.toContain('NON_ECHO_CANARY');

  let proxyTraps = 0, getterCalls = 0;
  const proxy = new Proxy({}, { ownKeys() { proxyTraps++; return []; }, getPrototypeOf() { proxyTraps++; return Object.prototype; } });
  expect(() => capturePresentationSchema({ nested: proxy }, 'proxy')).toThrowError(VictPresentationError);
  expect(proxyTraps).toBe(0);
  const getter = Object.defineProperty({}, 'secret', { enumerable: true, get() { getterCalls++; return 'value'; } });
  expect(() => capturePresentationSchema(getter, 'getter')).toThrowError(VictPresentationError);
  expect(getterCalls).toBe(0);
  expect(() => capturePresentationSchema(JSON.parse('{"constructor":1}'), 'prototype key')).toThrowError(VictPresentationError);
  const mutable = { type: 'object', description: 'Public description. '.repeat(300), properties: { code: { type: 'string' } } };
  let parseCount = 0, invokeCount = 0;
  const input = defineContract({ id: 'independent.input', revision: '1', descriptiveJsonSchema: mutable, parse(value: unknown) { parseCount++; return (value as { code?: string })?.code === 'allowed' ? { ok: true as const, value } : { ok: false as const, issues: [{ code: 'invalid', message: 'Exact code required' }] }; } });
  const capability = { id: 'independent.read', revision: '1', effect: 'read', input, invoke: async () => { invokeCount++; return {}; } };
  const activation = { activationVersion: 'v1_independent', agentProfileVersion: 'v1_profile', capabilities: [{ id: capability.id, revision: '1' }] };
  const tool = bridgeCapabilityToolToMastra(activation as never, capability as never, {} as never) as { inputSchema: { '~standard': { validate(value: unknown): { value?: unknown; issues?: unknown[] }; jsonSchema: { input(): unknown } } } };
  const standard = tool.inputSchema['~standard'], presented = standard.jsonSchema.input() as typeof mutable;
  expect(presented.description.length).toBeGreaterThan(2048);
  mutable.description = 'mutated';
  mutable.properties.code.type = 'number';
  expect(presented.description).not.toBe('mutated');
  expect(presented.properties.code.type).toBe('string');
  expect(Object.isFrozen(presented)).toBe(true);
  expect(Object.isFrozen(presented.properties.code)).toBe(true);
  expect(standard.validate({ code: 'forbidden' }).issues).toBeDefined();
  expect(standard.validate({ code: 'allowed' }).value).toEqual({ code: 'allowed' });
  expect(parseCount).toBe(2);
  expect(invokeCount).toBe(0);
  const sourcePaths = ['packages/mastra/src/presentation.ts', 'packages/mastra/src/compatibility.ts', 'apps/studio/src/lib/designer/agent-edit-presentation.ts', 'docs/report/VICT-PRESENTATION-STRING-BOUND-AMENDMENT-20261028.md'];
  const sourceHashes = Object.fromEntries(sourcePaths.map(path => [path, createHash('sha256').update(readFileSync(resolve(repository, path))).digest('hex')]));
  const report = { candidateSHA, amendmentSHA: '7152a897cb6b61f8fa32a2db9c60b99ca1f24cab', verdict: 'PASS - scoped direct presentation-string amendment', recipeCount: names.length, regexCharacters: pattern.length, editSerializedBytes: Buffer.byteLength(JSON.stringify(capturedEdit)), positiveCatalogProbes: names.length, rejectedUnknownCatalogProbes: unknown.length, validLongLeafCases: admitted.length, exactAggregateBoundary: { pass: 32768, refuse: 32769 }, earlyHugeLeafStringifyCalls: 0, proxyTrapCalls: proxyTraps, getterCalls, immutableProviderFacingCapture: true, authoritativeParseCalls: parseCount, capabilityInvokeCalls: invokeCount, adapterRevision: MASTRA_ADAPTER_REVISION, inheritedPresentationFindings, sourceHashes, limits: ['No live agent or provider request', 'No browser/server/build/dist action', 'Existing long catalog source restored byte-for-byte', 'Trailing-LF probes are reported separately; schema guidance never grants argument authority', 'Integrated acceptance remains HELD'] };
  writeFileSync(resolve(directory, 'string-amendment-independent-result.json'), JSON.stringify(report, null, 2) + '\n');
  console.log(JSON.stringify(report, null, 2));
});
